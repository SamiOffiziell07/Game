// Builds a small, dependency-free ZIP archive of the Kicko! source files in the browser.
const downloadButton = document.getElementById('download-btn');
const statusText = document.getElementById('download-status');

const crcTable = new Uint32Array(256);
for (let n = 0; n < 256; n++) {
  let value = n;
  for (let bit = 0; bit < 8; bit++) {
    value = (value & 1) ? (0xedb88320 ^ (value >>> 1)) : (value >>> 1);
  }
  crcTable[n] = value >>> 0;
}

function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) crc = (crc >>> 8) ^ crcTable[(crc ^ byte) & 0xff];
  return (crc ^ 0xffffffff) >>> 0;
}

function makeZip(files) {
  const encoder = new TextEncoder();
  const localParts = [];
  const centralParts = [];
  let localOffset = 0;
  let centralSize = 0;

  for (const file of files) {
    const name = encoder.encode(file.name);
    const data = file.data;
    const checksum = crc32(data);

    const localHeader = new Uint8Array(30);
    const localView = new DataView(localHeader.buffer);
    localView.setUint32(0, 0x04034b50, true);
    localView.setUint16(4, 20, true);
    localView.setUint16(6, 0x0800, true); // UTF-8 filenames
    localView.setUint16(8, 0, true); // Stored without compression
    localView.setUint16(10, 0, true);
    localView.setUint16(12, 33, true); // 1980-01-01
    localView.setUint32(14, checksum, true);
    localView.setUint32(18, data.length, true);
    localView.setUint32(22, data.length, true);
    localView.setUint16(26, name.length, true);
    localView.setUint16(28, 0, true);
    localParts.push(localHeader, name, data);
    localOffset += localHeader.length + name.length + data.length;

    const centralHeader = new Uint8Array(46);
    const centralView = new DataView(centralHeader.buffer);
    centralView.setUint32(0, 0x02014b50, true);
    centralView.setUint16(4, 20, true);
    centralView.setUint16(6, 20, true);
    centralView.setUint16(8, 0x0800, true);
    centralView.setUint16(10, 0, true);
    centralView.setUint16(12, 0, true);
    centralView.setUint16(14, 33, true);
    centralView.setUint32(16, checksum, true);
    centralView.setUint32(20, data.length, true);
    centralView.setUint32(24, data.length, true);
    centralView.setUint16(28, name.length, true);
    centralView.setUint16(30, 0, true);
    centralView.setUint16(32, 0, true);
    centralView.setUint16(34, 0, true);
    centralView.setUint16(36, 0, true);
    centralView.setUint32(38, 0, true);
    centralView.setUint32(42, localOffset - localHeader.length - name.length - data.length, true);
    centralParts.push(centralHeader, name);
    centralSize += centralHeader.length + name.length;
  }

  const endRecord = new Uint8Array(22);
  const endView = new DataView(endRecord.buffer);
  endView.setUint32(0, 0x06054b50, true);
  endView.setUint16(4, 0, true);
  endView.setUint16(6, 0, true);
  endView.setUint16(8, files.length, true);
  endView.setUint16(10, files.length, true);
  endView.setUint32(12, centralSize, true);
  endView.setUint32(16, localOffset, true);
  endView.setUint16(20, 0, true);

  return new Blob([...localParts, ...centralParts, endRecord], { type: 'application/zip' });
}

async function downloadProjectZip() {
  if (!downloadButton) return;
  downloadButton.disabled = true;
  if (statusText) statusText.textContent = 'Preparing your ZIP…';

  try {
    const paths = ['index.html', 'main.js', 'Input.js', 'Audio.js', 'Modifiers.js', 'download.js'];
    const files = await Promise.all(paths.map(async (path) => {
      const response = await fetch(new URL(`./${path}`, import.meta.url), { cache: 'no-store' });
      if (!response.ok) throw new Error(`Could not load ${path} (${response.status})`);
      return { name: path, data: new Uint8Array(await response.arrayBuffer()) };
    }));

    const readme = [
      'KICKO! POCKET SOCCER',
      '',
      'Project source files are in this folder. The field, players, ball, visuals, and sounds are generated by the game code.',
      '',
      'Run the game:',
      '1. Serve this folder with a local web server (ES modules need HTTP/HTTPS).',
      '2. Open index.html through that server in a modern browser.',
      '',
      'Three.js and the Fredoka font are loaded from online CDNs, so an internet connection is required.',
      '',
      'Controls: WASD or arrow keys to move, Space to shoot, Shift to pass. On touch devices use the on-screen controls.'
    ].join('\n');
    files.push({ name: 'README.txt', data: new TextEncoder().encode(readme) });

    const blob = makeZip(files);
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'kicko-pocket-soccer.zip';
    link.hidden = true;
    document.body.appendChild(link);
    link.click();
    link.remove();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
    if (statusText) statusText.textContent = 'ZIP downloaded.';
  } catch (error) {
    console.error('ZIP download failed:', error);
    if (statusText) statusText.textContent = 'ZIP could not be created. Please try again.';
  } finally {
    downloadButton.disabled = false;
  }
}

downloadButton?.addEventListener('click', downloadProjectZip);
